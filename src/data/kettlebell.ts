// Les 68 exercices des deux posters « Kettlebell Workouts » (volumes 1 et 2).
//
// Muscles : lus sur la planche anatomique de chaque case, comme pour les
// haltères — noir = principal, gris = secondaire. Trois exceptions, signalées
// sur place :
//   - les abducteurs (moyen fessier, tenseur du fascia lata) : la planche ne
//     les distingue pas du grand fessier ; on les déduit du mouvement — une
//     abduction de hanche, ou un appui sur une jambe qui oblige à tenir le
//     bassin ;
//   - le bas du dos sur la Superman et le Good Morning : la planche laisse les
//     érecteurs du rachis en gris clair, alors que l'extension du dos est
//     précisément leur travail. Corrigé ;
//   - deux cases dont la planche est illisible sur la photo (le relevé turc
//     en huit temps, le saut de bûche) : lecture déduite du mouvement.
//
// Les mouvements balistiques — swings, arraché, épaulé, sauts — sont marqués
// explosifs : la séance les écarte tant que l'option n'est pas cochée.
// Presque tous ces exercices se font aussi bien avec un haltère.

